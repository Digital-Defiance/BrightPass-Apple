/// Synchronously fetches a TOTP code from the mock API client using a detached task
/// to avoid MainActor deadlock.
private func fetchTOTPCodeSync(code: String, remaining: Int) -> String? {
    let mock = TOTPMockAPIClient()
    mock.nextCode = code
    mock.nextRemaining = remaining
    nonisolated(unsafe) var result: String?
    let semaphore = DispatchSemaphore(value: 0)
    Task.detached {
        let totpCode = try await mock.generateTOTP(secret: "JBSWY3DPEHPK3PXP")
        result = totpCode.code
        semaphore.signal()
    }
    semaphore.wait()
    return result
}

@available(macOS 14.0, iOS 17.0, *)
final class TOTPCodeFormatPropertyTests: XCTestCase {

    /// Property 14: TOTP Code Format — code is exactly 6 decimal digit characters.
    func testTOTPCodeIsExactlySixDecimalDigits() {
        property("TOTP code is exactly 6 decimal digits") <- forAllNoShrink(arbTotpDigitCode, arbRemainingSeconds) {
            (code: String, remaining: Int) in
            guard let received = fetchTOTPCodeSync(code: code, remaining: remaining) else {
                return false
            }
            let isLength6 = received.count == 6
            let allDigits = received.allSatisfy { $0.isNumber && $0.isASCII }
            return isLength6 && allDigits
        }
    }
}
