/// Generator for valid 6-digit TOTP codes (what a conforming API returns).
private let digitChars: [Character] = Array("0123456789")
private let arbTotpDigitCode: Gen<String> = Gen.compose { c in
    let digits = (0..<6).map { _ in c.generate(using: Gen<Character>.fromElements(of: digitChars)) }
    return String(digits)
}

/// Generator for remaining seconds in a TOTP period.
private let arbRemainingSeconds: Gen<Int> = Int.arbitrary.map { abs($0) % 30 + 1 }

